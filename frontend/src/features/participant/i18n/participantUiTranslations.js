/**
 * Build a translator for the given participant locale. Falls back to the
 * English table, then to the raw key, so a missing string is never blank.
 *
 * @param {'en' | 'he' | 'ar'} locale
 * @returns {(key: keyof typeof participantUiTranslations.en) => string}
 */
export function createParticipantT(locale) {
  const table = participantUiTranslations[locale] || participantUiTranslations.en;
  const fallback = participantUiTranslations.en;
  return (key) => table[key] ?? fallback[key] ?? key;
}

